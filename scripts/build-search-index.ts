/**
 * Writes src/content/lesson-index.generated.ts: one small entry per lesson (ids, title, summary, kind)
 * for every written topic. The app uses it for search, "up next" and badges without downloading
 * every topic's full content. Run by `npm run build:content`.
 */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { tracks } from "../src/content";
import type { IndexEntry } from "../src/lib/lessonIndex";

const entries: IndexEntry[] = [];
for (const track of tracks) {
  for (const topic of track.topics) {
    if (!topic.load) continue;
    const { lessons } = (await topic.load()).default;
    for (const lesson of lessons) {
      entries.push({
        track: track.id,
        topic: topic.id,
        id: lesson.id,
        kind: lesson.kind,
        title: lesson.title,
        summary: lesson.summary,
        ...(lesson.minutes ? { minutes: lesson.minutes } : {}),
      });
    }
  }
}

const output =
  `// AUTO-GENERATED by scripts/build-search-index.ts. Do not edit; run: npm run build:content\n\n` +
  `import type { IndexEntry } from "@/lib/lessonIndex";\n\n` +
  `export const lessonIndex: IndexEntry[] = [\n${entries.map((e) => `  ${JSON.stringify(e)},`).join("\n")}\n];\n`;

const target = "src/content/lesson-index.generated.ts";
if (!existsSync(target) || readFileSync(target, "utf8") !== output) writeFileSync(target, output);
console.log(`Search index: ${entries.length} lessons`);
